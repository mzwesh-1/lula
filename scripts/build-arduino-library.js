#!/usr/bin/env node
'use strict';
// Builds the "Soga" Arduino library: one header per language (isiZulu.h, isiXhosa.h, ...).
// A sketch in Arduino IDE that starts with `#include <isiZulu.h>` can then be written in isiZulu:
// the header turns every Soga word into the C++ Arduino word with the preprocessor.
//   node scripts/build-arduino-library.js            -> arduino-library/Soga/
const fs = require('fs');
const path = require('path');
const T = require('../src/translator');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'arduino-library', 'Soga');
const pkg = require(path.join(ROOT, 'package.json'));
const LANGS = [
  ['zu', 'isiZulu'], ['xh', 'isiXhosa'], ['ss', 'siSwati'], ['nr', 'isiNdebele'], ['st', 'Sesotho'],
  ['tn', 'Setswana'], ['nso', 'Sepedi'], ['ts', 'Xitsonga'], ['ve', 'Tshivenda'], ['af', 'Afrikaans'],
];
const ascii = w => w.normalize('NFD').replace(/[̀-ͯ]/g, '');

function header(code, file) {
  const lang = T.loadLanguage(code);
  const ctx = T.contextFor(code, [], { target: 'arduino', packs: ['arduino-libs'] });
  const words = new Map();
  for (const [local, cpp] of ctx.keywordMap) words.set(local, cpp);
  for (const [local, cpp] of ctx.libraryMap) if (!words.has(local)) words.set(local, cpp);
  const plain = [], unicode = [];
  const width = Math.max(...[...words.keys()].map(w => w.length));
  for (const [local, cpp] of [...words].sort((a, b) => a[0].localeCompare(b[0]))) {
    if (local === cpp) continue;
    if (/^[\x00-\x7f]+$/.test(local)) { plain.push(`#define ${local.padEnd(width)} ${cpp}`); continue; }
    unicode.push(`#define ${local.padEnd(width)} ${cpp}`);
    const a = ascii(local);   // the same word without accents, for older compilers (avr-gcc 7)
    if (/^\w+$/.test(a) && !words.has(a)) plain.push(`#define ${a.padEnd(width)} ${cpp}`);
  }
  const guard = `SOGA_${file.toUpperCase()}_H`;
  return `// ${file}.h - write Arduino sketches in ${lang.name}. Part of Soga ${pkg.version}.
// Generated by scripts/build-arduino-library.js from languages/${code}.json and packs/ - do not edit by hand.
//
// Put this as the FIRST line of your sketch, then write the rest in ${lang.name}:
//   #include <${file}.h>
// Include other libraries (Servo.h, Wire.h, ...) BEFORE this line.
#ifndef ${guard}
#define ${guard}
#if defined(SOGA_LANGUAGE)
#error "Soga: include only one language header in a sketch."
#endif
#define SOGA_LANGUAGE "${code}"
#include <Arduino.h>

${plain.join('\n')}
${unicode.length ? `
// Words with accents need a compiler that reads UTF-8 names (GCC 10+: ESP32, Pico, STM32...).
// On AVR boards (Uno, Nano, Mega) write them without the accents; both are defined.
#if defined(__GNUC__) && __GNUC__ >= 10
${unicode.join('\n')}
#endif
` : ''}
#endif // ${guard}
`;
}

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, 'src'), { recursive: true });
for (const [code, file] of LANGS) fs.writeFileSync(path.join(OUT, 'src', `${file}.h`), header(code, file));
fs.writeFileSync(path.join(OUT, 'src', 'Soga.h'), `// Soga: write Arduino code in the South African languages.
// Include ONE language header as the first line of your sketch:
${LANGS.map(([c, f]) => `//   #include <${f}.h>`).join('\n')}
#ifndef SOGA_H
#define SOGA_H
#include <Arduino.h>
#endif
`);
// keywords.txt: colours the words in Arduino IDE 1.8 (types/keywords KEYWORD1, functions KEYWORD2, constants LITERAL1)
const kwLines = new Set();
for (const [code] of LANGS) {
  const ctx = T.contextFor(code, [], { target: 'arduino', packs: ['arduino-libs'] });
  for (const [local] of ctx.keywordMap) kwLines.add(`${ascii(local)}\tKEYWORD1`);
  for (const [local, cpp] of ctx.libraryMap) if (!ctx.keywordMap.has(local)) kwLines.add(`${ascii(local)}\t${/^[A-Z0-9_]+$/.test(cpp) ? 'LITERAL1' : 'KEYWORD2'}`);
}
fs.writeFileSync(path.join(OUT, 'keywords.txt'), `# Soga words for Arduino IDE syntax colouring (generated)\n${[...kwLines].sort().join('\n')}\n`);
fs.writeFileSync(path.join(OUT, 'library.properties'), `name=Soga
version=${pkg.version}
author=Mzwandile Zulu, CMT Robotic Industries
maintainer=Mzwandile Zulu
sentence=Write Arduino sketches in isiZulu, isiXhosa, siSwati, isiNdebele, Sesotho, Setswana, Sepedi, Xitsonga, Tshivenda and Afrikaans.
paragraph=Add #include <isiZulu.h> (or your language) as the first line and write setup, loop, pinMode, digitalWrite, Serial and more in your home language.
category=Other
url=https://github.com/mzwesh-1/lula
architectures=*
includes=Soga.h
`);

// Examples: every .soga Arduino example in examples/, plus the same traffic light in every language
const exDir = path.join(OUT, 'examples');
const light = fs.readFileSync(path.join(ROOT, 'examples', 'irobhothi_lomgwaqo.zu.soga'), 'utf8');
const WIRING = '// Traffic light: green 10 s -> yellow 3 s -> red 5 s. Red pin 10, yellow pin 9, green pin 8 (220 ohm to GND).\n\n';
const lightCpp = T.translate(light, 'zu', { target: 'arduino', lineDirective: false }).cpp;
for (const [code, file] of LANGS) {
  const name = `AmalambuOmgwaqo_${file}`;
  fs.mkdirSync(path.join(exDir, name), { recursive: true });
  // Other languages: the code without the isiZulu comments, and without accents so it builds on AVR too
  const body = code === 'zu' ? light : WIRING + ascii(T.fromCpp(lightCpp, code).replace(/^[ \t]*\/\/.*\n/gm, '').replace(/[ \t]*\/\/.*$/gm, '').replace(/\n{3,}/g, '\n\n').replace(/\n\s*\n(\s*})/g, '\n$1').replace(/^\s+/, ''));
  fs.writeFileSync(path.join(exDir, name, `${name}.ino`), `#include <${file}.h>\n\n${body}`);
}
fs.writeFileSync(path.join(OUT, 'README.md'), `# Soga for Arduino IDE

Write Arduino sketches in your home language. Install this library (Sketch -> Include Library ->
Add .ZIP Library...), then make your language header the first line of the sketch:

\`\`\`cpp
#include <isiZulu.h>

ize qala() {
    setha_iphini(13, OKUPHUMAYO);
}

ize phindaphinda() {
    bhala_idijithali(13, PHEZULU);
    linda(1000);
    bhala_idijithali(13, PHANSI);
    linda(1000);
}
\`\`\`

Headers: ${LANGS.map(([, f]) => `\`${f}.h\``).join(', ')}.

- Put other libraries (\`#include <Servo.h>\`, \`<Wire.h>\`...) before your language header.
- \`#include\` lines stay in C++: the preprocessor reads them before any header can help.
- On AVR boards (Uno, Nano, Mega), write accented words without the accents (\`tsa\` for \`tša\`); both are defined.
- Compiler errors are shown in English in Arduino IDE. For errors in your language, use Soga in VS Code.
- The words are a draft that native speakers are still reviewing.
`);
console.log(`Soga Arduino library -> ${path.relative(ROOT, OUT)} (${LANGS.length} languages)`);
